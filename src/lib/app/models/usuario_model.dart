class UsuarioModel {
  final String nome;
  final String email;
  final String senha;
  final String cpf;
  final String telefone;
  final String cep;
  final String endereco;

  UsuarioModel({
    required this.nome,
    required this.email,
    required this.senha,
    required this.cpf,
    required this.telefone,
    required this.cep,
    required this.endereco,
  });
}